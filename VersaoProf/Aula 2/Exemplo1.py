
# Retorna um objeto do tipo str.
x = input("Digite um valor:")
print(f"Valor digitado = {x}")
print(f"Tipo do valor = {type(x)}")

# Transformar o objeto para int.
x = int(input("Digite um valor:"))
print(f"Valor digitado = {x}")
print(f"Tipo do valor = {type(x)}")

# Transformar (cast) o objeto para float.
x = float(input("Digite um valor:"))
print(f"Valor digitado = {x}")
print(f"Tipo do valor = {type(x)}")